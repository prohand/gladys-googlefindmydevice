// -----------------------------------------------------------------------------
// The account secrets, as GoogleFindMyTools writes them in `secrets.json`.
//
// Signing in to Google for this API needs a real Chrome window and, for the
// end-to-end encryption keys, the screen-lock PIN of one of the user's Android
// devices: none of that can happen inside a headless container. So the user
// runs GoogleFindMyTools once on a computer and pastes the resulting
// `secrets.json` into the integration. The fields used:
//   - username          the Google account e-mail
//   - aas_token         the long-lived master token (exchanged for API tokens)
//   - fcm_credentials   the push channel identity (android_id, security
//                       token, FCM token, Web Push keys)
//   - owner_key         (hex) decrypts the devices' identity keys; present
//                       once a location was decrypted by GoogleFindMyTools
// Every one of them is a credential: never log them.
// -----------------------------------------------------------------------------

import { ecdhFromPrivateKey } from './ece.js';

/** Error whose message is a multi-language object, shown to the user as is. */
export class SecretsError extends Error {
  constructor(message) {
    super(message.en);
    this.userMessage = message;
  }
}

const MESSAGES = {
  missing: {
    en: 'Paste the content of the secrets.json file generated by GoogleFindMyTools.',
    fr: 'Collez le contenu du fichier secrets.json généré par GoogleFindMyTools.',
    de: 'Füge den Inhalt der von GoogleFindMyTools erzeugten Datei secrets.json ein.',
    es: 'Pegue el contenido del archivo secrets.json generado por GoogleFindMyTools.',
  },
  invalidJson: {
    en: 'The secrets.json content is not valid JSON: paste the whole file, from { to }.',
    fr: "Le contenu de secrets.json n'est pas un JSON valide : collez tout le fichier, de { à }.",
    de: 'Der Inhalt von secrets.json ist kein gültiges JSON: Füge die ganze Datei ein, von { bis }.',
    es: 'El contenido de secrets.json no es un JSON válido: pegue todo el archivo, de { a }.',
  },
  incomplete: (fields) => ({
    en: `secrets.json is incomplete (missing: ${fields}). Run GoogleFindMyTools again until it lists your devices.`,
    fr: `secrets.json est incomplet (manque : ${fields}). Relancez GoogleFindMyTools jusqu'à ce qu'il liste vos appareils.`,
    de: `secrets.json ist unvollständig (fehlt: ${fields}). Starte GoogleFindMyTools erneut, bis es deine Geräte auflistet.`,
    es: `secrets.json está incompleto (falta: ${fields}). Vuelva a ejecutar GoogleFindMyTools hasta que liste sus dispositivos.`,
  }),
};

function pick(object, path) {
  return path.split('.').reduce((value, part) => value?.[part], object);
}

const REQUIRED = [
  'username',
  'aas_token',
  'fcm_credentials.gcm.android_id',
  'fcm_credentials.gcm.security_token',
  'fcm_credentials.fcm.registration.token',
  'fcm_credentials.keys.private',
  'fcm_credentials.keys.secret',
];

/**
 * Parse and check the pasted secrets.
 * @param {string | object} raw the config value (a JSON string)
 * @returns {{ username: string, aasToken: string, androidId: string,
 *   securityToken: string, fcmToken: string, privateKey: string,
 *   authSecret: string, ownerKey: Buffer | null }}
 * @throws {SecretsError}
 */
export function parseSecrets(raw) {
  if (raw === undefined || raw === null || String(raw).trim() === '') {
    throw new SecretsError(MESSAGES.missing);
  }
  let data = raw;
  if (typeof raw === 'string') {
    try {
      data = JSON.parse(raw);
    } catch {
      throw new SecretsError(MESSAGES.invalidJson);
    }
  }
  if (!data || typeof data !== 'object') {
    throw new SecretsError(MESSAGES.invalidJson);
  }
  // Older firebase-messaging versions stored the credentials as a JSON string.
  if (typeof data.fcm_credentials === 'string') {
    try {
      data = { ...data, fcm_credentials: JSON.parse(data.fcm_credentials) };
    } catch {
      throw new SecretsError(MESSAGES.invalidJson);
    }
  }
  const missing = REQUIRED.filter((path) => {
    const value = pick(data, path);
    return value === undefined || value === null || String(value) === '';
  });
  if (missing.length > 0) {
    throw new SecretsError(MESSAGES.incomplete(missing.join(', ')));
  }
  const ownerKeyHex = typeof data.owner_key === 'string' ? data.owner_key.trim() : '';
  const ownerKey = /^([0-9a-f]{2}){16,64}$/i.test(ownerKeyHex)
    ? Buffer.from(ownerKeyHex, 'hex')
    : null;
  const credentials = data.fcm_credentials;
  try {
    // The push keys are used at every message: refuse a broken one now.
    ecdhFromPrivateKey(String(credentials.keys.private));
  } catch {
    throw new SecretsError(MESSAGES.incomplete('fcm_credentials.keys.private'));
  }
  return {
    username: String(data.username),
    aasToken: String(data.aas_token),
    androidId: String(credentials.gcm.android_id),
    securityToken: String(credentials.gcm.security_token),
    fcmToken: String(credentials.fcm.registration.token),
    privateKey: String(credentials.keys.private),
    authSecret: String(credentials.keys.secret),
    ownerKey,
  };
}

/** The e-mail with its local part masked, for logs and messages. */
export function maskEmail(email) {
  const [local, domain] = String(email).split('@');
  if (!domain) {
    return '***';
  }
  return `${local.slice(0, 2)}***@${domain}`;
}
